DO $$
BEGIN
    CREATE TYPE moderation_action as ENUM ('review_comment_hide', 'review_comment_unhide');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;

CREATE TABLE IF NOT EXISTS moderation_log(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_account_id INTEGER NOT NULL REFERENCES accounts(id),
    action moderation_action NOT NULL,
    -- One nullable FK column per target kind; exactly one must be set.
    target_review_id INTEGER REFERENCES reviews(id),
    reason TEXT NOT NULL CHECK (length(reason) > 0),
    details JSONB NOT NULL DEFAULT '{}',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT moderation_log_one_target CHECK (num_nonnulls(target_review_id) = 1)
);

CREATE INDEX IF NOT EXISTS moderation_log_review ON moderation_log(target_review_id, created_at) WHERE target_review_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS moderation_log_actor ON moderation_log(actor_account_id, created_at);

